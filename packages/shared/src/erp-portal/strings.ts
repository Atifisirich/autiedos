export type StringKey = keyof typeof S;
export const PORTAL_STRINGS: Readonly<Record<StringKey, Entry>> = S;
export const STRING_KEYS = Object.keys(S) as StringKey[];
const ph = (s: string): string => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');

/** Looks up a string; falls back to English, then to the key itself (so a typo shows up on screen instead of crashing). */
export function lookup(lang: PortalLang, key: string, params?: Record<string, string | number>): string {
  const e = (S as Record<string, Entry | undefined>)[key];
  const raw = e ? e[lang] || e.en : key;
  return params ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : raw;
}
export const makeL = (lang: PortalLang) => (key: StringKey | (string & {}), params?: Record<string, string | number>): string => lookup(lang, key, params);

/** Catalogue self-check used by the unit test: every language present, same placeholders, no empty string. */
export function catalogueProblems(): string[] {
  const out: string[] = [];
  for (const [k, e] of Object.entries(S as Record<string, Entry>)) {
    for (const l of ['en', 'hi', 'te'] as const) {
      if (!e[l] || !e[l].trim()) out.push(`${k}: empty ${l}`);
      else if (ph(e[l]) !== ph(e.en)) out.push(`${k}: placeholders differ in ${l}`);
    }
  }
  return out;
}
