#!/usr/bin/env node
// Builds the demo data files for the hosted staging project (docs/staging.md) from a LOCAL database that was built with
//   pnpm db:reset  +  ERP_DEMO_DOMAIN=erp.demo.school node scripts/seed-erp-demo.mjs && node scripts/seed-erp-demo-extras.mjs  +  CRM seed
// Output: supabase/staging/NN-*.sql, each under ~1 MB, applied in name order on Supabase (Supabase MCP / SQL editor).
//   00-auth.sql    the demo logins in auth.users + auth.identities (columns that exist on real Supabase; no passwords)
//   01-truncate.sql empties core, os, crm, erp, billing on the target (migration catalogue rows come back with the data)
//   NN-data.sql    data only for core, os, crm, erp, billing (audit and private are not copied)
// Every data file starts with `set session_replication_role = replica` (no FK checks, no triggers, so no audit rows) and
// the order of the files does not matter for foreign keys. Demo accounts only: the seeds create no real people.
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.DATABASE_URL ?? 'postgres://postgres@localhost:54322/staging';
const out = join(root, 'supabase/staging');
const SCHEMAS = ['core', 'os', 'crm', 'erp', 'billing'];
const LIMIT = 1_000_000;

mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) if (f.endsWith('.sql')) rmSync(join(out, f));

const c = new pg.Client({ connectionString: url });
await c.connect();
const lit = (v) => (v === null || v === undefined ? 'null' : c.escapeLiteral(typeof v === 'string' ? v : JSON.stringify(v)));
const ts = (v) => (v ? lit(new Date(v).toISOString()) : 'null');

// ---------------------------------------------------------------- auth
const users = (await c.query('select id, email, phone, raw_user_meta_data, created_at from auth.users order by created_at, id')).rows;
let auth = '-- Demo logins (generated by scripts/export-staging-data.mjs). Passwords are set separately, never stored here.\n';
auth += 'delete from auth.identities where user_id in (select id from auth.users where id = any(array[' + users.map((u) => lit(u.id) + '::uuid').join(',') + ']));\n';
auth += 'delete from auth.users where id = any(array[' + users.map((u) => lit(u.id) + '::uuid').join(',') + ']);\n';
auth += `insert into auth.users (instance_id, id, aud, role, email, phone, raw_user_meta_data, raw_app_meta_data, created_at, updated_at, email_confirmed_at,
  confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token, reauthentication_token) values\n`;
auth += users.map((u) => `('00000000-0000-0000-0000-000000000000', ${lit(u.id)}, 'authenticated', 'authenticated', ${lit(u.email)}, ${lit(u.phone)}, ${lit(u.raw_user_meta_data ?? {})}::jsonb, '{"provider":"email","providers":["email"]}'::jsonb, ${ts(u.created_at)}, ${ts(u.created_at)}, ${u.email ? ts(u.created_at) : 'null'}, '', '', '', '', '', '', '', '')`).join(',\n') + ';\n';
const withEmail = users.filter((u) => u.email);
auth += 'insert into auth.identities (provider_id, user_id, identity_data, provider, created_at, updated_at) values\n';
auth += withEmail.map((u) => `(${lit(u.id)}, ${lit(u.id)}, ${lit({ sub: u.id, email: u.email, email_verified: true, phone_verified: false })}::jsonb, 'email', ${ts(u.created_at)}, ${ts(u.created_at)})`).join(',\n') + ';\n';
writeFileSync(join(out, '00-auth.sql'), auth);

// ---------------------------------------------------------------- truncate
const tables = (await c.query(`select format('%I.%I', schemaname, tablename) t from pg_tables where schemaname = any($1) order by 1`, [SCHEMAS])).rows.map((r) => r.t);
writeFileSync(join(out, '01-truncate.sql'), `-- Empties the platform product schemas before the data files are loaded (cascade: private rows that point at them).\nset session_replication_role = replica;\ntruncate ${tables.join(', ')} cascade;\n`);

// ---------------------------------------------------------------- data
const dump = execFileSync('pg_dump', ['--dbname', url, '--data-only', '--column-inserts', '--rows-per-insert=100', '--no-owner', '--no-privileges', ...SCHEMAS.flatMap((s) => ['-n', s])], { maxBuffer: 1 << 30, stdio: ['ignore', 'pipe', 'ignore'] }).toString('utf8');
// Keep only INSERT and setval statements (pg_dump's SET header assumes a superuser session).
const stmts = [];
let cur = null;
for (const line of dump.split('\n')) {
  if (cur === null) {
    if (line.startsWith('INSERT INTO ') || line.startsWith('SELECT pg_catalog.setval(')) cur = [line];
    else continue;
  } else cur.push(line);
  if (line.endsWith(';')) { stmts.push(cur.join('\n')); cur = null; }
}
const head = '-- Demo data (generated by scripts/export-staging-data.mjs).\nset session_replication_role = replica;\n';
let n = 2, buf = head;
const flush = () => { writeFileSync(join(out, `${String(n).padStart(2, '0')}-data.sql`), buf); n += 1; buf = head; };
for (const s of stmts) {
  if (buf.length + s.length > LIMIT && buf !== head) flush();
  buf += s + '\n';
}
if (buf !== head) flush();

// ---------------------------------------------------------------- expected counts
const counts = [];
for (const t of tables) counts.push([t, Number((await c.query(`select count(*) n from ${t}`)).rows[0].n)]);
writeFileSync(join(out, 'counts.json'), JSON.stringify({ 'auth.users': users.length, 'auth.identities': withEmail.length, ...Object.fromEntries(counts) }, null, 1) + '\n');
console.log(`${users.length} users, ${tables.length} tables, ${stmts.length} statements, ${n - 2} data files`);
await c.end();
